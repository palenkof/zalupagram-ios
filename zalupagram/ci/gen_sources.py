#!/usr/bin/env python3
# ZalupaGram: generates ZalupaGramGenerated.swift for //submodules/ZalupaGram.
#
# The version comes from zalupagram/version.json. The read-only token for
# the private releases repo comes from zalupagram/update_token.txt, which
# only exists on the build machine (GitHub Actions writes it from the
# UPDATE_TOKEN secret) and is never committed. It is XOR-masked with a
# key, so it is not a plain string in the binary. This is not real
# protection: anyone with the IPA can still get it, the token can only read
# the releases repo.

import argparse
import json
import os
import hashlib


def swift_bytes(data):
    return '[' + ', '.join(str(b) for b in data) + ']'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--version', required=True)
    parser.add_argument('--token-files', default='')
    parser.add_argument('--out', required=True)
    args = parser.parse_args()

    with open(args.version) as f:
        version = json.load(f)['version']

    token = b''
    for path in args.token_files.split():
        if os.path.isfile(path):
            with open(path, 'rb') as f:
                token = f.read().strip()

    # Deterministic, so Bazel can reuse what depends on this file.
    key = b''
    block = b'zalupagram'
    while len(key) < len(token):
        block = hashlib.sha256(block + token).digest()
        key += block
    key = key[:len(token)]
    masked = bytes(a ^ b for a, b in zip(token, key))

    with open(args.out, 'w') as f:
        f.write('// Generated by zalupagram/ci/gen_sources.py, do not edit.\n')
        f.write('let zalupaGramVersion = "%s"\n' % version)
        f.write('let zalupaGramUpdateTokenMasked: [UInt8] = %s\n' % swift_bytes(masked))
        f.write('let zalupaGramUpdateTokenKey: [UInt8] = %s\n' % swift_bytes(key))


if __name__ == '__main__':
    main()
